import matplotlib.pyplot as plt

# 1. 准备你的真实数据
# 这里的字典键是题目 (Q1-Q10)，值是一个列表，代表选 1分、2分、3分、4分、5分 的人数。
# 【注意】因为你的实验组只有 10 人，所以每个列表里的数字加起来必须等于 10！
# 下面我为你生成了一组模拟的测试数据：
data = {
    'Q1': [0, 0, 0, 2, 8],
    'Q2': [0, 0, 0, 2, 8],
    'Q3': [0, 0, 0, 1, 9],
    'Q4': [0, 0, 0, 4, 6],
    'Q5': [0, 0, 0, 1, 9],
    'Q6': [0, 0, 0, 1, 9],
    'Q7': [0, 0, 0, 2, 8],
    'Q8': [0, 0, 0, 1, 9]
}

# 2. 创建画布和子图网格 (4行2列)
# figsize 控制整个图片的宽和高，你可以根据论文排版需要调整
fig, axes = plt.subplots(nrows=4, ncols=2, figsize=(8, 7))

# 将 4x3 的矩阵展平为一维列表，方便我们循环遍历
axes = axes.flatten()

x_labels = [1, 2, 3, 4, 5]

# 3. 循环遍历数据并画图
for i, (q_name, counts) in enumerate(data.items()):
    ax = axes[i]
    
    # 画柱状图，width=0.5 用来控制柱子的粗细，让它看起来像原图一样清爽
    ax.bar(x_labels, counts, width=0.5)
    
    # 设置子图标题 (Q1, Q2...)
    ax.set_title(q_name)
    
    # 强制 x 轴刻度只显示 1, 2, 3, 4, 5
    ax.set_xticks(x_labels)
    
    # 强制 y 轴刻度 (针对你的 10 人样本量，刻度设为 0, 2, 4, 6, 8, 10 即可)
    # 如果你想强行复刻原图的 20 刻度，改成 [0, 4, 8, 12, 16, 20] 即可
    ax.set_yticks([0, 2, 4, 6, 8, 10])

# 4. (无需删除空白子图，网格已按 8 个子图创建)

# 5. 自动调整子图之间的间距，防止文字重叠
plt.tight_layout()

# 6. 显示图片 (你可以在弹出的窗口中直接点击保存为 .png，然后插入 Word)
plt.show()